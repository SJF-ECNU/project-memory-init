import { _electron as electron } from 'playwright'
import electronPath from 'electron'
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, copyFile, chmod, rm, realpath, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
const data = await mkdtemp(path.join(tmpdir(), 'init-electron-data-'))
const root = await realpath(await mkdtemp(path.join(tmpdir(), 'init UI project ')))
const bin = path.join(data, 'bin'); await mkdir(bin)
for (const name of ['claude', 'codex']) { await copyFile('tests/fake-agent.cjs', path.join(bin, name)); await chmod(path.join(bin, name), 0o755) }
await writeFile(path.join(root, 'README.md'), '# 初始化测试项目\n真实进程传输的界面测试，不代表模型初始化质量。')
await mkdir('test-results', { recursive: true })
let app
try {
  app = await electron.launch({ executablePath: electronPath, args: ['.', `--user-data-dir=${data}`, `--project=${root}`], env: { ...process.env, PATH: bin + path.delimiter + process.env.PATH } })
  const page = await app.firstWindow()
  const settle = () => page.waitForFunction(() => !document.querySelector(".view-enter-active, .view-leave-active, .results-enter-active, .results-leave-active"))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.getByRole('button', { name: '一键初始化', exact: true }).click()
  await settle()
  await page.getByRole('button', { name: '开始初始化', exact: true }).waitFor()
  await page.locator('nav').getByRole('button', { name: /^项目概览/ }).click()
  await settle()
  await page.getByRole('heading', { name: '项目概览', exact: true }).waitFor()
  assert.equal(await page.locator('.init-page').count(), 0)
  await page.getByRole('button', { name: '一键初始化', exact: true }).click()
  await settle()
  await page.getByRole('button', { name: '返回文件浏览' }).focus()
  await page.keyboard.press('Escape')
  await settle()
  assert.equal(await page.locator('.init-page').count(), 0)
  await page.getByRole('button', { name: '一键初始化', exact: true }).click()
  await settle()
  await page.getByRole('radio', { name: /Claude Code/ }).check()
  await page.getByRole('button', { name: '开始初始化', exact: true }).click()
  await settle()
  await page.getByRole('status').getByText('初始化执行完成，已检查必要入口文件').waitFor()
  await page.screenshot({ path: 'test-results/initialization.png' })
  await page.getByRole('button', { name: '返回文件浏览' }).click()
  await settle()
  await page.locator('nav').getByRole('button', { name: /^全部内容/ }).click()
  await settle()
  assert.ok(await page.locator('.file-card').count() > 10)
  await page.locator('nav').getByRole('button', { name: /^CLAUDE.md/ }).click()
  await settle()
  assert.equal(await page.locator('.file-card').count(), 1)
  await page.getByRole('button', { name: '一键初始化', exact: true }).click()
  await settle()
  await page.getByRole('radio', { name: /Codex/ }).check()
  assert.equal(await page.getByLabel('本次使用的模型').inputValue(), 'test-supported-model')
  await writeFile(path.join(root, 'fixture-mode.txt'), 'failure')
  await page.getByRole('button', { name: '重新执行初始化' }).click()
  await settle()
  await page.getByText('请先登录：authentication required', { exact: true }).waitFor()
  await page.getByRole('status').getByText(/Agent 未完成初始化/).waitFor()
  const args = JSON.parse(await readFile(path.join(root, 'received-args.json'), 'utf8'))
  assert.equal(args[args.indexOf('--model') + 1], 'test-supported-model')
  await writeFile(path.join(root, 'fixture-mode.txt'), 'wait')
  await page.getByRole('button', { name: '重新执行初始化' }).click()
  await settle()
  await page.getByText('正在调查项目', { exact: true }).waitFor()
  await page.locator('nav').getByRole('button', { name: /^CLAUDE.md/ }).click()
  await settle()
  assert.equal(await page.locator('.init-page').count(), 0)
  await page.getByRole('button', { name: '初始化进行中' }).click()
  await settle()
  await page.getByRole('button', { name: '停止执行' }).click()
  await settle()
  await page.getByRole('status').getByText('已停止；已写入的文件会保留', { exact: true }).waitFor()
  assert.equal(await page.evaluate(async () => { try { await window.initialization.start('/', 'claude'); return false } catch { return true } }), true)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(800, 720))
  await page.screenshot({ path: 'test-results/initialization-narrow.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ passed: true, execution: 'fake CLI processes', checks: ['agent detection and selection', 'start', 'streaming', 'outputs refresh', 'failure', 'reopen active job', 'cancellation', 'IPC boundary', 'narrow layout'] }))
} catch(error) {
  if (app) { const page = await app.firstWindow(); await page.screenshot({ path: 'test-results/initialization-failure.png' }); console.log((await page.locator('main').innerText()).slice(-2500)) }
  throw error
} finally { if (app) await app.close(); await rm(data, { recursive: true, force: true }); await rm(root, { recursive: true, force: true }) }
