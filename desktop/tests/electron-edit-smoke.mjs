import { _electron as electron } from 'playwright'
import electronPath from 'electron'
import assert from 'node:assert/strict'
import { mkdtemp, writeFile, readFile, rm, mkdir, utimes } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
const data = await mkdtemp(path.join(tmpdir(), 'edit-ui-data-'))
const root = await mkdtemp(path.join(tmpdir(), 'edit-ui-project-'))
await writeFile(path.join(root, 'README.md'), '# 原始标题\n原始内容')
await writeFile(path.join(root, 'notes.txt'), '# Literal\n<script>window.infected=true</script>')
await writeFile(path.join(root, '.gitignore'), 'dist/\nnode_modules/')
await mkdir('test-results', { recursive:true })
const calendar = new Date(); calendar.setHours(12, 0, 0, 0)
for (const [name, days] of [['yesterday', -1], ['this-week', -3], ['older', -40], ['future', 2]]) {
  const time = new Date(calendar); time.setDate(time.getDate() + days)
  const filename = path.join(root, `${name}.txt`)
  await writeFile(filename, name); await utimes(filename, time, time)
}
let app
try {
  app = await electron.launch({ executablePath:electronPath, args:['.', `--user-data-dir=${data}`, `--project=${root}`] })
  const page = await app.firstWindow()
  const settle = () => page.waitForFunction(() => !document.querySelector('.view-enter-active,.view-leave-active,.results-enter-active,.results-leave-active'))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.locator('.time-group-heading').first().waitFor()
  for (const label of ['今天', '昨天', '近 7 天', '更早', '未来日期']) assert.ok(await page.locator('.time-group-heading').filter({hasText:label}).count())
  assert.ok(/\d{4}/.test(await page.locator('.card-date').first().innerText()), 'card date includes year')
  await page.getByLabel('文件排序').selectOption('name')
  assert.equal(await page.locator('.time-group-heading').count(), 0)
  await page.getByLabel('文件排序').selectOption('updated')
  await page.locator('.file-card').filter({hasText:'原始标题'}).click(); await settle()
  await page.getByRole('button', {name:'编辑文件',exact:true}).click()
  await page.getByLabel('文件内容编辑').fill('# 更新标题\n保存后的正文')
  await app.evaluate(({dialog}) => { dialog.showMessageBox = async () => ({response:0}); dialog.showMessageBoxSync = () => 0 })
  await page.locator('nav').getByRole('button', {name:/^全部内容/}).click()
  assert.equal(await page.getByLabel('文件内容编辑').inputValue(), '# 更新标题\n保存后的正文')
  assert.equal(await page.evaluate(() => { const event = new Event('beforeunload', {cancelable:true}); window.dispatchEvent(event); return event.defaultPrevented }), true, 'dirty draft prevents unload')
  await page.screenshot({path:'test-results/editor.png'})
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+s' : 'Control+s')
  await page.locator('.file-editor').waitFor({state:'detached'})
  assert.equal(await readFile(path.join(root,'README.md'),'utf8'), '# 更新标题\n保存后的正文')
  assert.ok((await page.locator('.markdown').innerText()).includes('保存后的正文'))
  await page.getByRole('button', {name:/返回 全部内容/}).click(); await settle()
  assert.ok((await page.locator('.file-card').filter({hasText:'更新标题'}).innerText()).includes('保存后的正文'))
  await page.locator('.file-card').filter({hasText:'notes.txt'}).click(); await settle()
  assert.equal(await page.locator('.plain-content').innerText(), '# Literal\n<script>window.infected=true</script>')
  assert.equal(await page.locator('.plain-content script').count(),0)
  await page.getByRole('button',{name:'编辑文件',exact:true}).click()
  await page.getByLabel('文件内容编辑').fill('我的草稿')
  await writeFile(path.join(root,'notes.txt'),'外部程序更新')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'其他程序修改'}).waitFor()
  assert.equal(await page.getByLabel('文件内容编辑').inputValue(),'我的草稿')
  assert.equal(await readFile(path.join(root,'notes.txt'),'utf8'),'外部程序更新')
  await app.evaluate(({dialog}) => { dialog.showMessageBox = async () => ({response:1}) })
  await page.getByRole('button',{name:/返回 全部内容/}).click(); await settle()
  await page.locator('.file-card').filter({hasText:'.gitignore'}).click(); await settle()
  await page.getByRole('button',{name:'编辑文件',exact:true}).click()
  await page.getByLabel('文件内容编辑').fill('build/\n')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await page.locator('.file-editor').waitFor({state:'detached'})
  assert.equal(await readFile(path.join(root,'.gitignore'),'utf8'),'build/\n')
  assert.equal(await page.evaluate(async () => { try {await window.projects.save('/', '.env', 'x', ''); return false} catch {return true} }),true)
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({passed:true, checks:['calendar time groups and complete dates','ungrouped name sorting','Markdown save and preview','shortcut','card update','plain text safety','dotfile save','discard cancellation','unsaved unload prevention','external conflict preserves draft','write IPC boundary']}))
} finally { if(app) await app.close(); await rm(data,{recursive:true,force:true}); await rm(root,{recursive:true,force:true}) }
